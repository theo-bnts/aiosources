"""Rebuild bundled notices from the installed, locked runtime dependencies.

Run after npm ci, npm run build and go mod download. No license is inferred from
its identifier: missing license files fail generation for a maintainer to review.
"""

import hashlib
import json
import pathlib
import subprocess


ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web/public/THIRD-PARTY-NOTICES.txt"
SNAPSHOTS = json.loads((ROOT / "licenses/upstream.json").read_text())


def snapshot_text(identity):
    snapshot = SNAPSHOTS.get(identity)
    if snapshot is None:
        raise RuntimeError("Review missing license files: " + identity)
    data = (ROOT / "licenses" / snapshot["file"]).read_bytes()
    if hashlib.sha256(data).hexdigest() != snapshot["sha256"]:
        raise RuntimeError("Original upstream license snapshot changed: " + identity)
    return data.decode("utf-8").strip()


def license_text(directory, identity):
    files = sorted(
        p
        for p in directory.iterdir()
        if p.is_file()
        and p.name.lower().split(".")[0] in ("license", "licence", "copying", "notice")
    )
    if not files:
        return snapshot_text(identity)
    return "\n\n".join(p.read_text(encoding="utf-8").strip() for p in files)


def modules():
    result = subprocess.check_output(
        ["go", "list", "-deps", "-json", "-tags", "production", "./cmd/ingest"],
        cwd=ROOT,
        text=True,
    )
    decoder = json.JSONDecoder()
    found = {}
    while result.strip():
        value, length = decoder.raw_decode(result.lstrip())
        result = result.lstrip()[length:]
        module = value.get("Module")
        if not module or module.get("Main"):
            continue
        key = module["Path"] + " " + module.get("Version", "local")
        directory = pathlib.Path(module.get("Replace", module)["Dir"])
        found[key] = directory
    return sorted(found.items())


def frontend():
    lock = json.loads((ROOT / "web/package-lock.json").read_text())
    found = {}
    for path, entry in lock["packages"].items():
        # Vite's preload helpers and Tailwind's reset styles are emitted into
        # the distributed bundle even though their packages are build tools.
        emitted = path.rsplit("node_modules/", 1)[-1] in ("vite", "tailwindcss")
        if not path or (entry.get("dev") and not emitted):
            continue
        directory = ROOT / "web" / path
        package_file = directory / "package.json"
        if not package_file.is_file():
            if entry.get("optional"):
                continue
            raise RuntimeError("Install locked dependencies: " + path)
        package = json.loads(package_file.read_text())
        key = package["name"] + " " + package["version"]
        found[key] = directory
    return sorted(found.items())


def section(title, dependencies):
    groups = {}
    for name, directory in dependencies:
        text = license_text(directory, name)
        key = hashlib.sha256(text.encode()).hexdigest()
        entry = groups.setdefault(key, {"names": [], "text": text})
        entry["names"].append(name)
    blocks = [title, "=" * len(title)]
    for entry in sorted(groups.values(), key=lambda item: item["names"][0]):
        blocks.extend(["\n" + "\n".join(entry["names"]), entry["text"]])
    return "\n\n".join(blocks)


def main():
    certificate = "Alpine ca-certificates-bundle 20260909-r0"
    builders = [
        line.split()[2]
        for line in (ROOT / "Dockerfile").read_text().splitlines()
        if line.startswith("FROM --platform=$BUILDPLATFORM golang:")
    ]
    if builders != [SNAPSHOTS[certificate]["builder"]]:
        raise RuntimeError("Review certificate-bundle source and notices for the changed builder")
    go_modules, packages = modules(), frontend()
    goroot = pathlib.Path(
        subprocess.check_output(["go", "env", "GOROOT"], cwd=ROOT, text=True).strip()
    )
    blocks = [
        "AIOSources — licenses and third-party notices",
        "Generated by tools/generate-notices.py from locked runtime dependencies.\n"
        "Original notices are reproduced below; third-party components retain their licenses.",
        "AIOSources, Ingest and the Torznab SDK\n\n" + (ROOT / "LICENSE").read_text().strip(),
        "TMDB attribution\n\n"
        "This product uses the TMDB API but is not endorsed or certified by TMDB.\n"
        "The unchanged approved TMDB logo is used for attribution under TMDB's branding terms,\n"
        "not under the software's MIT license. API access and data have separate terms.\n"
        "https://developer.themoviedb.org/docs/faq\n"
        "https://www.themoviedb.org/about/logos-attribution",
        "Go standard library\n\n" + (goroot / "LICENSE").read_text().strip(),
        (goroot / "PATENTS").read_text().strip(),
        section("Go runtime modules", go_modules),
        section("Frontend libraries, fonts and emitted build helpers", packages),
        snapshot_text(certificate),
    ]
    # Upstream Markdown notices sometimes carry trailing spaces. Normalize
    # whitespace only; preserve every copyright, term and additional notice.
    text = "\n".join(line.rstrip() for line in "\n\n".join(blocks).splitlines())
    OUTPUT.write_text(text + "\n", encoding="utf-8")
    print("Bundled notices:", len(go_modules), "Go modules;", len(packages), "frontend packages")


if __name__ == "__main__":
    main()
